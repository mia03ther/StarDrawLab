import { useCallback, useEffect, useState } from "react";
import toast from "react-hot-toast";
import useAuthAxios from "../hooks/useAuthAxios";
import { useLanguage } from "../contexts/LanguageContext";
import { useStarDrawTheme } from "../utils/stardrawTheme";

const statusLabel = (status, t) => ({
  active: t("已连接", "Connected"),
  error: t("需要重新授权", "Reauthorization required"),
  revoked: t("已断开", "Revoked"),
}[status] || status || "—");
const approvalLabel = (policy, t) => ({ policy: t("按权限确认", "policy"), always: t("始终确认", "always") }[policy] || policy || "—");

const McpConnections = () => {
  const authAxios = useAuthAxios();
  const { t } = useLanguage();
  const { ui } = useStarDrawTheme();
  const [servers, setServers] = useState([]);
  const [connections, setConnections] = useState([]);
  const [tools, setTools] = useState({});
  const [loading, setLoading] = useState(true);
  const [busyKey, setBusyKey] = useState("");

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const [serverResponse, connectionResponse] = await Promise.all([
        authAxios.get("/api/mcp/servers"),
        authAxios.get("/api/mcp/connections"),
      ]);
      setServers(serverResponse.data?.data || []);
      setConnections(connectionResponse.data?.data || []);
    } catch (error) {
      toast.error(error.response?.data?.message || t("MCP 连接信息加载失败", "Unable to load MCP connections"));
    } finally {
      setLoading(false);
    }
  }, [authAxios, t]);

  useEffect(() => { void load(); }, [load]);

  const connect = async (serverKey) => {
    setBusyKey(`connect:${serverKey}`);
    try {
      const { data } = await authAxios.post("/api/mcp/connections/start", { serverKey });
      const authorizationUrl = data?.data?.authorizationUrl;
      if (!authorizationUrl) throw new Error(t("服务端没有返回授权地址", "The server did not return an authorization URL"));
      // The URL is generated by the server from discovered OAuth metadata.
      window.location.assign(authorizationUrl);
    } catch (error) {
      toast.error(error.response?.data?.message || error.message || t("无法开始授权", "Unable to start authorization"));
      setBusyKey("");
    }
  };

  const revoke = async (connection) => {
    if (!window.confirm(t("确认断开这个 MCP 账号？服务端会同时撤销本地连接。", "Disconnect this MCP account? The server will revoke the local connection too."))) return;
    setBusyKey(`revoke:${connection.id}`);
    try {
      await authAxios.post(`/api/mcp/connections/${encodeURIComponent(connection.id)}/revoke`);
      toast.success(t("MCP 连接已断开", "MCP connection revoked"));
      await load();
    } catch (error) {
      toast.error(error.response?.data?.message || t("断开连接失败", "Unable to revoke connection"));
    } finally {
      setBusyKey("");
    }
  };

  const loadTools = async (connectionId) => {
    setBusyKey(`tools:${connectionId}`);
    try {
      const { data } = await authAxios.get(`/api/mcp/connections/${encodeURIComponent(connectionId)}/tools`);
      setTools((current) => ({ ...current, [connectionId]: data?.data || [] }));
    } catch (error) {
      toast.error(error.response?.data?.message || t("工具列表加载失败", "Unable to load tools"));
    } finally {
      setBusyKey("");
    }
  };

  return (
    <main className="mx-auto max-w-7xl p-6 md:p-8">
      <div className="mb-8 flex flex-wrap items-end justify-between gap-4">
        <div>
          <p className="text-[10px] font-black uppercase tracking-[0.24em]" style={{ color: ui.primary }}>{t("MCP 连接", "MCP CONNECT")}</p>
          <h1 className="mt-2 text-4xl font-black" style={{ color: ui.text }}>{t("MCP 连接", "MCP Connections")}</h1>
          <p className="mt-3 max-w-2xl text-sm leading-6" style={{ color: ui.faint }}>
            {t("连接后，Agent 只能使用你自己授权的第三方账号。StarDraw 不会要求你把 API Token 粘贴到网页中。", "After connecting, the Agent can only use your own authorized third-party account. StarDraw never asks you to paste an API token into the browser.")}
          </p>
        </div>
        <button type="button" onClick={() => void load()} disabled={loading} className="rounded-xl px-4 py-2.5 text-sm font-black disabled:opacity-50" style={{ background: ui.surface, color: ui.text, border: `1px solid ${ui.line}` }}>
          {loading ? t("加载中…", "Loading…") : t("刷新", "Refresh")}
        </button>
      </div>

      <div className="grid gap-6 xl:grid-cols-[1fr,1.1fr]">
        <section className="rounded-3xl p-5" style={{ background: ui.surface, border: `1px solid ${ui.line}`, boxShadow: ui.shadow }}>
          <div className="mb-4 flex items-center justify-between">
            <div>
              <h2 className="text-lg font-black" style={{ color: ui.text }}>{t("可用服务", "Available services")}</h2>
              <p className="mt-1 text-xs" style={{ color: ui.faint }}>{t("服务由 root 配置并经过平台白名单审核。", "Services are configured and allowlisted by root.")}</p>
            </div>
            <span className="rounded-full px-2.5 py-1 text-[10px] font-black" style={{ background: ui.primarySoft, color: ui.primary }}>{servers.length}</span>
          </div>
          <div className="space-y-3">
            {servers.length === 0 && !loading && <div className="rounded-2xl p-8 text-center text-sm" style={{ background: ui.surfaceAlt, color: ui.faint }}>{t("暂时没有可连接的 MCP 服务。", "No MCP services are currently available.")}</div>}
            {servers.map((server) => {
              const connected = connections.some((item) => item.serverKey === server.serverKey && item.status === "active");
              return (
                <div key={server.serverKey} className="flex items-center justify-between gap-4 rounded-2xl p-4" style={{ background: ui.surfaceAlt, border: `1px solid ${ui.line}` }}>
                  <div className="min-w-0">
                    <p className="truncate font-black" style={{ color: ui.text }}>{server.displayName || server.serverKey}</p>
                    <p className="mt-1 text-xs" style={{ color: ui.faint }}>{server.providerAdapter} · {server.transport}</p>
                  </div>
                  <button type="button" onClick={() => void connect(server.serverKey)} disabled={connected || busyKey === `connect:${server.serverKey}`} className="shrink-0 rounded-xl px-3 py-2 text-xs font-black disabled:cursor-not-allowed disabled:opacity-50" style={{ background: connected ? ui.surface : ui.buttonGradient, color: connected ? ui.muted : ui.primaryText, border: connected ? `1px solid ${ui.line}` : "none" }}>
                    {connected ? t("已连接", "Connected") : busyKey === `connect:${server.serverKey}` ? t("跳转中…", "Redirecting…") : t("连接", "Connect")}
                  </button>
                </div>
              );
            })}
          </div>
        </section>

        <section className="rounded-3xl p-5" style={{ background: ui.surface, border: `1px solid ${ui.line}`, boxShadow: ui.shadow }}>
          <div className="mb-4">
            <h2 className="text-lg font-black" style={{ color: ui.text }}>{t("我的连接", "My connections")}</h2>
            <p className="mt-1 text-xs" style={{ color: ui.faint }}>{t("每个连接都绑定当前登录用户，其他用户和管理员不能代用。", "Every connection is bound to the signed-in user and cannot be used by other users or administrators.")}</p>
          </div>
          <div className="space-y-3">
            {connections.length === 0 && !loading && <div className="rounded-2xl p-8 text-center text-sm" style={{ background: ui.surfaceAlt, color: ui.faint }}>{t("你还没有连接 MCP 账号。", "You have no connected MCP accounts.")}</div>}
            {connections.map((connection) => (
              <div key={connection.id} className="rounded-2xl p-4" style={{ background: ui.surfaceAlt, border: `1px solid ${ui.line}` }}>
                <div className="flex items-start justify-between gap-4">
                  <div className="min-w-0">
                    <p className="truncate font-black" style={{ color: ui.text }}>{connection.serverKey || t("MCP 服务", "MCP service")}</p>
                    <p className="mt-1 truncate text-xs" style={{ color: ui.faint }}>{connection.providerAccountId || t("默认账号", "Primary account")}</p>
                  </div>
                  <span className="rounded-full px-2.5 py-1 text-[10px] font-black" style={{ background: connection.status === "active" ? "rgba(82,216,122,.13)" : ui.dangerSoft, color: connection.status === "active" ? ui.success : ui.danger }}>{statusLabel(connection.status, t)}</span>
                </div>
                <div className="mt-4 flex flex-wrap gap-2">
                  <button type="button" onClick={() => void loadTools(connection.id)} disabled={busyKey === `tools:${connection.id}`} className="rounded-lg px-3 py-2 text-xs font-bold" style={{ background: ui.primarySoft, color: ui.primary }}>{busyKey === `tools:${connection.id}` ? t("加载中…", "Loading…") : t("查看允许的工具", "View allowed tools")}</button>
                  <button type="button" onClick={() => void revoke(connection)} disabled={busyKey === `revoke:${connection.id}`} className="rounded-lg px-3 py-2 text-xs font-bold" style={{ background: ui.dangerSoft, color: ui.danger }}>{t("断开", "Disconnect")}</button>
                </div>
                {tools[connection.id] && <div className="mt-4 space-y-2 border-t pt-3" style={{ borderColor: ui.line }}>
                  {tools[connection.id].length === 0 ? <p className="text-xs" style={{ color: ui.faint }}>{t("管理员尚未启用工具。", "No tools have been enabled by an administrator.")}</p> : tools[connection.id].map((tool) => <div key={tool.toolName} className="flex items-center justify-between gap-3 rounded-xl px-3 py-2" style={{ background: ui.surface, border: `1px solid ${ui.line}` }}><span className="truncate text-xs font-bold" style={{ color: ui.text }}>{tool.toolName}</span><span className="shrink-0 text-[10px]" style={{ color: ui.faint }}>{approvalLabel(tool.approvalPolicy, t)}</span></div>)}
                </div>}
              </div>
            ))}
          </div>
        </section>
      </div>
    </main>
  );
};

export default McpConnections;
